//! Якорь доверия для шлюза брокера (§14).
//!
//! Шлюз Т-Инвестиций предъявляет сертификат, выпущенный удостоверяющим
//! центром Минцифры, которого нет в общедоступных хранилищах доверия.
//! Корень этого центра вшит в двоичный файл и передаётся **только**
//! клиенту Т-Инвестиций: корень, добавленный в системное хранилище,
//! начинает ручаться за любой узел, а не только за шлюз брокера.
//!
//! Проверка подлинности при этом **не отключается**. Клиент проверяет
//! цепочку как обычно — меняется лишь то, откуда берётся якорь.
//! Ни `danger_accept_invalid_certs`, ни иных послаблений здесь нет.
//!
//! Происхождение файла и порядок его замены описаны в `certs/README.md`.

use reqwest::{Certificate, Client};
use thiserror::Error;

/// Корневой сертификат Минцифры.
///
/// `include_str!`, а не чтение файла при запуске: файл на диске рядом
/// с программой подменить проще, чем содержимое двоичного файла,
/// а якорь доверия — ровно то, что подменяют в первую очередь.
pub const RUSSIAN_TRUSTED_ROOT_CA_PEM: &str = include_str!("../certs/russian-trusted-root-ca.pem");

#[derive(Debug, Error)]
pub enum TrustError {
    #[error("вшитый корень доверия не разобран: {0}")]
    RootNotParsed(String),
    #[error("клиент шлюза не собран: {0}")]
    ClientNotBuilt(String),
}

/// Сколько сертификатов лежит в вшитой связке.
///
/// Ровно один: промежуточный сертификат сервер присылает сам, а лишний
/// якорь — это лишнее доверие и вторая дата истечения.
#[must_use]
pub fn certificate_count() -> usize {
    RUSSIAN_TRUSTED_ROOT_CA_PEM
        .matches("BEGIN CERTIFICATE")
        .count()
}

/// Якорь доверия для шлюза Т-Инвестиций.
pub fn tls_root() -> Result<Certificate, TrustError> {
    Certificate::from_pem(RUSSIAN_TRUSTED_ROOT_CA_PEM.as_bytes())
        .map_err(|error| TrustError::RootNotParsed(error.to_string()))
}

/// HTTP-клиент шлюза Т-Инвестиций.
///
/// Встроенные корни выключены намеренно: клиент ходит к одному
/// удостоверяющему центру, и доверять он должен ровно ему. Веб-корни,
/// оставленные включёнными, расширили бы доверие на весь публичный
/// интернет ради узла, которому это не нужно.
pub fn tinkoff_client() -> Result<Client, TrustError> {
    Client::builder()
        .tls_backend_rustls()
        // Именно `only`, а не `merge`: `merge` добавил бы наш корень
        // к веб-корням, и клиент продолжил бы доверять всему публичному
        // интернету ради узла, которому это не нужно.
        .tls_certs_only([tls_root()?])
        .build()
        .map_err(|error| TrustError::ClientNotBuilt(error.to_string()))
}
