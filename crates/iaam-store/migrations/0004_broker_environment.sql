-- Среда брокерского канала (§14).
--
-- У песочницы и боя Т-Инвестиций РАЗНЫЕ токены: боевой токен на песочном
-- шлюзе отвечает 401 «Authentication token is missing or invalid», а
-- песочный в боевой среде — отказом. Значит две среды требуют двух
-- одновременно действующих доступов, чего прежний уникальный индекс
-- по паре владелец+брокер не позволял.
--
-- Среда хранится строкой и толкуется в iaam-broker — по той же причине,
-- по которой хранилище не толкует область прав: оно хранит, а не решает.
--
-- Умолчание `prod` относится к УЖЕ существующим строкам: они заведены
-- до появления сред, и боевая среда для них единственное честное
-- предположение. Новые строки среду называют явно.

ALTER TABLE broker_access ADD COLUMN environment TEXT NOT NULL DEFAULT 'prod';

-- Индекс перезаводится, а не дополняется: условие уникальности изменилось.
-- Один действующий доступ на тройку владелец+брокер+среда; второй означал
-- бы, что неизвестно, каким из них система ходит в эту среду.
DROP INDEX broker_access_active;

CREATE UNIQUE INDEX broker_access_active
    ON broker_access (owner, broker, environment)
    WHERE revoked_at IS NULL;
