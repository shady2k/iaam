-- 0009: словарь видов операций канала (эпик iaam-d8b.2.2).
--
-- Соответствие «код источника → вид операции» до сих пор было вшито
-- в match: tinkoff/parse.rs знал 34 кода, и пополнение словаря требовало
-- релиза. API брокера меняется без нашего участия, коды добавляются,
-- и код, узнающий об этом только при отклонённой строке импорта,
-- узнаёт об этом слишком поздно.
--
-- Данные никуда не переносятся: новая таблица, пустая.
--
-- Владельца в ключе НЕТ намеренно. Словарь — факт о брокерском API,
-- а не о владельце: OPERATION_TYPE_COUPON означает купон у всех, кто
-- ходит в T-Invest. Владельческий столбец сделал бы один и тот же
-- факт разным у разных владельцев, а расхождение было бы неотличимо
-- от решения.
CREATE TABLE broker_operation_kinds (
    -- Код брокера — тот же, каким названы доступы (broker_access).
    broker      TEXT NOT NULL,
    -- Как вид назвал сам канал: OPERATION_TYPE_COUPON и подобное.
    -- Множество открыто и брокеру принадлежит, поэтому текст без CHECK.
    source_kind TEXT NOT NULL,
    -- Во что это превращается у нас. Список закрыт: он повторяет
    -- ChannelOperationKind, а тот меняется только вместе с кодом.
    -- Члена 'other' здесь нет намеренно: «вид, которого нет в словаре»
    -- выражается ОТСУТСТВИЕМ строки, и строка с таким видом означала бы
    -- решение не разбирать — а такого решения не принимали.
    kind        TEXT NOT NULL,
    -- Откуда строка взялась. Без этого решение владельца неотличимо
    -- от автоматического заполнения, и обновление словаря молча затрёт
    -- первое вторым.
    origin      TEXT NOT NULL,
    -- Чем назвался источник словаря: версия контракта, ревизия, дата —
    -- то, по чему потом отвечают на вопрос «откуда мы это взяли».
    -- У решения владельца источника нет, поэтому NULL допустим.
    dictionary  TEXT,
    recorded_at TEXT NOT NULL,
    PRIMARY KEY (broker, source_kind),
    CHECK (origin IN ('contract', 'owner')),
    CHECK (kind IN (
        'buy', 'sell', 'dividend', 'coupon', 'commission',
        'deposit', 'withdrawal', 'transfer',
        'bond_amortisation', 'bond_redemption'
    ))
) STRICT;
